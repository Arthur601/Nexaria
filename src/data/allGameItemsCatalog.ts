/**
 * Instancia um item do catálogo para inclusão direta no inventário do personagem.
 */
export function createInventoryItemFromCatalog(
  catalogItem: CatalogItemDefinition,
  quantity: number = 1
): InventoryItem {
  return {
    id: `item-${catalogItem.id}-${Date.now()}-${Math.random().toString(36).substring(2, 6)}`,
    name: catalogItem.name,
    category: catalogItem.category,
    rarity: catalogItem.rarity,
    quantity: Math.max(1, quantity),
    weightKg: catalogItem.weightKg,
    effectText: catalogItem.effectText,
    description: catalogItem.description,
    valueAmount: catalogItem.valueAmount,
    valueCurrency: catalogItem.valueCurrency,
    iconEmoji: catalogItem.iconEmoji,
    equipped: false,
    durability: catalogItem.durability ? { ...catalogItem.durability } : undefined,
  };
}

