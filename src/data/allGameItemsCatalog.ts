export function searchCatalogItems(params: {
  query?: string;
  category?: ItemCategory | 'all';
  rarity?: ItemRarity | 'all';
  sortBy?: 'name' | 'rarity' | 'price_asc' | 'price_desc' | 'weight';
}): CatalogItemDefinition[] {
  let list = [...ALL_GAME_ITEMS_CATALOG];

  if (params.category && params.category !== 'all') {
    list = list.filter((i) => i.category === params.category);
  }

  if (params.rarity && params.rarity !== 'all') {
    list = list.filter((i) => i.rarity === params.rarity);
  }

  if (params.query && params.query.trim()) {
    const q = params.query.toLowerCase().trim();
    list = list.filter(
      (i) =>
        i.name.toLowerCase().includes(q) ||
        i.description.toLowerCase().includes(q) ||
        i.effectText.toLowerCase().includes(q) ||
        i.subcategory.toLowerCase().includes(q) ||
        (i.properties && i.properties.toLowerCase().includes(q))
    );
  }

  const rarityRank: Record<ItemRarity, number> = {
    comum: 1,
    incomum: 2,
    raro: 3,
    epico: 4,
    lendario: 5,
    abissal: 6,
  };

  const currencyValueInBrz: Record<CurrencyType, number> = {
    BRZ: 1,
    PRT: 10,
    ORO: 100,
    PLN: 1000,
    CYB: 5000,
  };

  if (params.sortBy === 'name') {
    list.sort((a, b) => a.name.localeCompare(b.name));
  } else if (params.sortBy === 'rarity') {
    list.sort((a, b) => rarityRank[b.rarity] - rarityRank[a.rarity]);
  } else if (params.sortBy === 'price_asc') {
    list.sort(
      (a, b) =>
        a.valueAmount * currencyValueInBrz[a.valueCurrency] -
        b.valueAmount * currencyValueInBrz[b.valueCurrency]
    );
  } else if (params.sortBy === 'price_desc') {
    list.sort(
      (a, b) =>
        b.valueAmount * currencyValueInBrz[b.valueCurrency] -
        a.valueAmount * currencyValueInBrz[a.valueCurrency]
    );
  } else if (params.sortBy === 'weight') {
    list.sort((a, b) => a.weightKg - b.weightKg);
  }

  return list;
}

