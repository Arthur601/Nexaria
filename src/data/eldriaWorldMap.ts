/**
 * Busca informações completas de uma região pelo seu identificador ou idioma.
 */
export function getRegionById(id: string): OriginRegionInfo | undefined {
  if (!id) return undefined;
  const clean = id.toLowerCase().trim();
  return ORIGIN_REGIONS.find(
    (r) => r.id === clean || r.name.toLowerCase() === clean || r.language.toLowerCase() === clean
  );
}

/**
 * Traduz um texto caractere por caractere para a forma rúnica da região.
 */
export function translateTextToRunes(
  text: string,
  regionId: string = 'caeldrin'
): Array<{ original: string; runeSymbol: string; runeName: string; runeMeaning: string }> {
  const alphabet = REGIONAL_RUNIC_ALPHABETS[regionId] || REGIONAL_RUNIC_ALPHABETS['caeldrin'];

  const results: Array<{ original: string; runeSymbol: string; runeName: string; runeMeaning: string }> = [];

  for (const char of text) {
    const upper = char.toUpperCase();
    if (alphabet[upper]) {
      const g = alphabet[upper];
      results.push({
        original: char,
        runeSymbol: g.symbol,
        runeName: g.name,
        runeMeaning: g.meaning,
      });
    } else {
      // Caracteres não alfabéticos ou espaços
      results.push({
        original: char,
        runeSymbol: char === ' ' ? ' ' : char,
        runeName: char === ' ' ? 'Espaço Rúnico' : 'Símbolo Rúnico',
        runeMeaning: 'Pausa Mística',
      });
    }
  }

  return results;
}
